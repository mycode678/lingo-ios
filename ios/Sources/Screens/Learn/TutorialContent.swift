import Foundation

/// 教程内容。用户原话：
/// > 我想在app里提供一个中国人提高英语听力的教程……用大白话讲解英语母语人士说英语的方式、
/// > 中国人听英语/说英语的常见错误及如何改进
/// > 要理论结合实际来讲，拿真音频举例说明理论，教程中可点击播放音频。
/// > 教程要做到重点突出、逻辑清晰、简明实用。
/// > 教程配套练习也是必要和重要的设计
///
/// **内容直接写在代码里，不放服务器**（用户说"先放201，能独立集成到app最好"）。
/// 理由：教程一共几十 KB，随包走就不用管网络、不用管服务器活着没有，
/// 也符合"完全脱离服务器"这条大方向。
///
/// 例子怎么"拿真音频"：每个例子给一个**关键词组**，App 到用户装好的材料里
/// 现找一句包含它的真句子来放（`TutorialService.find`）。这样例子永远是真人音频，
/// 而不是我预先录一段假的；用户装了什么材料就拿什么举例。
enum Tutorial {

    struct Lesson: Identifiable {
        var id: String
        var title: String
        var oneLine: String            // 一句话说清这一课要解决什么
        var blocks: [Block]
    }

    enum Block {
        /// 正文（大白话，一段一句话说清一件事）
        case text(String)
        /// 敲黑板：这一课最该记住的
        case key(String)
        /// 真音频例子：到装好的材料里找一句包含 `phrase` 的，点了就播
        case example(phrase: String, why: String)
        /// 配套练习：跳到对应的练法
        case practice(TrainMode, String)
        /// 常见错误对照表：中国人怎么念 vs 母语者怎么念
        case compare(cn: String, native: String)
    }

    static let lessons: [Lesson] = [

        Lesson(id: "beat", title: "第 1 课　英语是打拍子的，中文是数格子的",
               oneLine: "抓住这一条，后面七课都是它的推论。",
               blocks: [
            .text("中文里，每个字占的时间差不多长，像数格子：「我-今-天-去-北-京」，六个格子六拍。"),
            .text("英语不是。英语只有**重读的音节**才占一拍，中间那些虚词全被塞进拍子的缝里。"
                  + "所以 “I'm going to Beijing today” 听起来只有三四拍，"
                  + "不是七个词七拍。"),
            .key("英语的节奏由重读音节决定，跟词的多少关系不大。"
                 + "两句话词数差一倍，说出来可能一样长。"),
            .text("这就是为什么你觉得母语者"说得快"——他们不是每个词都念快了，"
                  + "而是把不重要的词压扁了。"),
            .example(phrase: "can you", why: "听 can you 有多短——它被压进了两个重读词中间的缝里"),
            .practice(.stress, "只听重读词：把非重读的压到 20%，你会发现照样听得懂")
        ]),

        Lesson(id: "weak", title: "第 2 课　虚词会被吞掉（弱读）",
               oneLine: "你听不出来的那些词，多半是 a / the / to / of / for。",
               blocks: [
            .text("英语里 the、to、of、for、and、can、was 这些词，正常语速下几乎听不见完整的音，"
                  + "元音会退化成一个模糊的 “ə”（就是"呃"那个音）。"),
            .compare(cn: "to　念成清清楚楚的「兔」", native: "to　念成一个几乎听不见的「特」"),
            .compare(cn: "and　念成「安德」", native: "and　经常只剩一个 n"),
            .key("虚词不是让你听清的，是让你**猜出来**的。"
                 + "母语者自己也没听清，他们靠语法补。"),
            .text("这条直接决定了一个学习策略：**别在虚词上较劲**。"
                  + "把耳朵留给实词，虚词交给语法。"),
            .example(phrase: "the", why: "同一个 the，在句子里可能只有 60 毫秒"),
            .practice(.blank, "盲听填空：挖掉的空全是被弱读的词——先体会一下有多难")
        ]),

        Lesson(id: "link", title: "第 3 课　连读：词和词之间没有缝",
               oneLine: "「每个词都认识，连起来不认识」，九成是这个原因。",
               blocks: [
            .text("英文写出来词和词之间有空格，说出来没有。前一个词的尾音直接滑进下一个词。"),
            .compare(cn: "an apple　念成「安 · 苹果」", native: "an apple　念成「呃-N阿婆」"),
            .compare(cn: "for his　念成「否 · 黑斯」", native: "for his　念成一个词 /fərɪz/"),
            .text("三种最常见的连读：辅音接元音（把辅音送过去）、"
