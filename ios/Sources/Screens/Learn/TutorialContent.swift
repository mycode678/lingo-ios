            .key("你听到「有个坑」的地方，往往就是一个没炸开的辅音。"
                 + "把它当成一个信号，而不是噪音。"),
            .text("说的时候也一样：中国人爱把词尾的辅音念得又重又长（还常常多加一个元音，"
